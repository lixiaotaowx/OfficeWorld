const { chromium } = require('./playwright.cjs');
const { createServer } = require('vite');
const react = require('@vitejs/plugin-react');
const assert = require('node:assert/strict');
const { resolve } = require('node:path');
(async () => {
  const vite = await createServer({ configFile: false, root: resolve('.'), plugins: [react()], server: { host: '127.0.0.1', port: 0 } });
  await vite.listen();
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 560, height: 780 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/test/dock-meeting-harness.html`);
    await page.waitForFunction(() => window.__pushState);
    const members = [{id:'me',name:'小桃1',status:'joined'}, {id:'c',name:'CCC',status:'invited'}];
    const push = patch => page.evaluate(patch => window.__pushState({ ...window.__dockState,
      meeting: { ...window.__dockState.meeting, ...patch } }), {members, ...patch});
    const invite = { id: 'meeting-1', personId: 'p1', name: 'CCC' };
    await push({ invitations: [invite] });
    await page.getByText('CCC发起的会议', { exact: true }).waitFor();
    assert.equal(await page.locator('.dock-stage[data-mode=call][data-greeting=p1]').count(), 1);
    await page.waitForTimeout(4100);
    assert.equal(await page.locator('.dock-call').count(), 1, 'meeting invite persists past ordinary greeting timeout');
    await page.locator('.dock-call-answer').click();
    assert.deepEqual((await page.evaluate(() => window.__actions.at(-1))).slice(0, 2), ['meeting-accept', 'meeting-1']);
    await push({ active: true, id: 'meeting-1', host: true, title: '办公室讨论', invitations: [] });
    await page.locator('.dock-meeting-panel').waitFor();
    assert.equal(await page.getByLabel('小桃1，已加入').textContent(), '小桃1✓');
    assert.equal(await page.getByLabel('CCC，等待加入').textContent(), 'CCC◷');
    assert.equal(await page.getByText('办公室讨论', {exact:true}).count(), 0);
    await push({active:true,id:'meeting-1',host:true,members:[members[0],{...members[1],status:'joined'}]});
    assert.equal(await page.getByLabel('CCC，已加入').textContent(), 'CCC✓');
    assert.equal(await page.locator('.dock-call').count(), 0);
    assert.equal(await page.getByLabel('关闭会议小窗口').count(), 0);
    await page.getByLabel('折叠会议小窗口').click();
    const folded = page.getByLabel('展开会议小窗口');
    await folded.waitFor();
    assert.equal(await page.locator('.dock-meeting-panel').count(), 0);
    const tiny = await folded.boundingBox(); assert.ok(tiny.width <= 28 && tiny.height <= 24);
    await push({ active: true, id: 'meeting-1', host: true, title: '办公室讨论' });
    await folded.click();
    await page.getByRole('button', { name: '离开会议', exact: true }).click();
    await page.getByRole('button', { name: '确认离开', exact: true }).click();
    assert.equal(await page.evaluate(() => window.__actions.at(-1)[0]), 'meeting-leave');
    await page.getByRole('button', { name: '结束会议', exact: true }).click();
    await page.getByRole('button', { name: '确认结束', exact: true }).click();
    assert.equal(await page.evaluate(() => window.__actions.at(-1)[0]), 'meeting-end');
    await page.screenshot({ path: resolve('../Build/dock-meeting-controls.png') });
    await push({ active: true, id: 'meeting-1', host: false, title: '办公室讨论' });
    assert.equal(await page.getByRole('button', { name: '结束会议', exact: true }).isDisabled(), true);
    await push({ active: false, invitations: [invite] });
    await page.locator('.dock-call-decline').click();
    assert.equal(await page.evaluate(() => window.__actions.at(-1)[0]), 'meeting-decline');
    await page.screenshot({ path: resolve('../Build/dock-meeting-invite.png') });
    await push({ active: false, invitations: [] });
    await page.waitForFunction(() => !document.querySelector('.dock-call') && !document.querySelector('.dock-meeting-panel'));
    assert.deepEqual(errors, []);
    console.log('PASS meeting role greeting, accept/decline, persistent fold, host controls, cleanup');
  } finally { await browser.close(); await vite.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
