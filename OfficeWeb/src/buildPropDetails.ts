import type { PropBox } from './buildPropFurniture';
export function propDetails(kind: string, b: PropBox) {
  const cream='#f3dfc5', wood='#c69770', ink='#424b5b', leaf='#78936c', light='#ffe3a1';
  function book(x:number,y:number,z:number,w:number,d:number,color?:string) {
    for (const top of [0.012,0.085]) b([w,0.024,d],[x,y+top,z],color);
    b([w-0.02,0.05,d-0.025],[x,y+0.049,z],cream);
    b([0.026,0.09,d],[x-w/2+0.013,y+0.045,z],color);
  }
  function pot() {
    b([0.26,0.21,0.26],[0,0.105,0]);
    b([0.29,0.05,0.29],[0,0.215,0]);
    b([0.23,0.015,0.23],[0,0.245,0],'#75604c');
  }
  switch(kind) {
    case 'books-stack':
      book(0,0,0,0.3,0.38,'#78936c');
      book(0.02,0.1,0.01,0.32,0.34,'#b9c9df');
      book(-0.015,0.2,0,0.29,0.36);
      break;
    case 'books-upright':
      for(let i=0;i<4;i++) {
        const h=0.33+(i%2)*0.06,x=-0.135+i*0.09;
        b([0.075,h,0.25],[x,h/2,0],[undefined,'#cabddd',wood,'#b4c5a0'][i]);
        b([0.055,0.012,0.01],[x,h-0.065,0.13],cream);
      }
      break;
    case 'magazine':
      b([0.32,0.018,0.43],[0,0.009,0],cream);
      b([0.32,0.007,0.43],[0,0.0215,0]);
      b([0.25,0.004,0.18],[0,0.027,0.065],'#b9c9df');
      for(let i=0;i<3;i++) b([0.22-i*0.045,0.003,0.016],[-i*0.0225,0.027,-0.16+i*0.027],cream);
      break;
    case 'mug':
      b([0.16,0.17,0.16],[0,0.085,0]);
      b([0.125,0.008,0.125],[0,0.174,0],'#705543');
      for(const y of [0.035,0.14]) b([0.09,0.025,0.06],[0.11,y,0]);
      b([0.025,0.13,0.06],[0.155,0.085,0]);
      break;
    case 'drink-cup':
      b([0.14,0.07,0.14],[0,0.035,0]);
      b([0.17,0.16,0.17],[0,0.15,0]);
      b([0.174,0.055,0.174],[0,0.13,0],cream);
      b([0.19,0.025,0.19],[0,0.2425,0],cream);
      b([0.013,0.16,0.013],[0.025,0.335,0],wood);
      break;
    case 'water-bottle':
      b([0.13,0.22,0.13],[0,0.11,0],'#b9c9df');
      b([0.08,0.07,0.08],[0,0.255,0],'#b9c9df');
      b([0.09,0.035,0.09],[0,0.3075,0]);
      b([0.135,0.065,0.135],[0,0.14,0],cream);
      break;
    case 'popcorn':
      b([0.24,0.12,0.24],[0,0.06,0]);
      b([0.3,0.2,0.3],[0,0.22,0]);
      for(const x of [-0.09,0.03]) {
        b([0.05,0.19,0.012],[x,0.22,0.156],cream);
        b([0.012,0.19,0.05],[0.156,0.22,x],cream);
      }
      for(let i=0;i<4;i++) for(let j=0;j<4;j++) {
        const h=0.055+((i*3+j)%3)*0.016;
        b([0.064,h,0.064],[-0.108+i*0.072,0.32+h/2,-0.108+j*0.072],(i+j)%3 ? cream : light);
      }
      b([0.07,0.07,0.07],[0.025,0.43,0],cream);
      break;
    case 'snack-bowl':
      b([0.24,0.04,0.24],[0,0.02,0]);
      for(const x of [-0.135,0.135]) b([0.03,0.08,0.3],[x,0.06,0]);
      for(const z of [-0.135,0.135]) b([0.24,0.08,0.03],[0,0.06,z]);
      for(let i=0;i<3;i++) b([0.07,0.045,0.16],[-0.08+i*0.08,0.065,0],'#e7bd77');
      break;
    case 'serving-tray':
      b([0.6,0.025,0.4],[0,0.0125,0]);
      for(const x of [-0.285,0.285]) b([0.03,0.07,0.4],[x,0.06,0]);
      for(const z of [-0.185,0.185]) b([0.54,0.04,0.03],[0,0.045,z]);
      break;
    case 'tissue-box':
      b([0.25,0.11,0.16],[0,0.055,0]);
      b([0.12,0.01,0.025],[0,0.115,0],ink);
      b([0.085,0.07,0.014],[0,0.15,0],cream);
      b([0.06,0.015,0.055],[0.01,0.188,0],cream);
      break;
    case 'remote':
      b([0.07,0.025,0.21],[0,0.0125,0]);
      b([0.025,0.005,0.025],[0,0.0275,-0.065],'#e9b8b5');
      for(let i=0;i<3;i++) for(const x of [-0.016,0.016]) b([0.018,0.005,0.018],[x,0.0275,-0.01+i*0.032],cream);
      break;
    case 'photo-frame':
      b([0.35,0.43,0.045],[0,0.215,0]);
      b([0.29,0.36,0.014],[0,0.215,0.029],cream);
      b([0.22,0.14,0.008],[0,0.13,0.04],'#b4c5a0');
      b([0.07,0.07,0.01],[0.06,0.3,0.04],light);
      b([0.12,0.045,0.15],[0,0.0225,-0.06],wood);
      break;
    case 'desk-clock':
      b([0.28,0.25,0.07],[0,0.145,0]);
      b([0.22,0.19,0.01],[0,0.145,0.04],cream);
      b([0.012,0.075,0.008],[0,0.178,0.049],ink);
      b([0.075,0.012,0.008],[0.031,0.145,0.049],ink);
      for(const x of [-0.08,0.08]) b([0.05,0.02,0.065],[x,0.01,0],wood);
      break;
    case 'table-light':
      b([0.22,0.035,0.22],[0,0.0175,0]);
      b([0.2,0.16,0.2],[0,0.115,0],light,true);
      b([0.14,0.045,0.14],[0,0.2175,0],light,true);
      break;
    case 'floor-light':
      b([0.35,0.07,0.35],[0,0.035,0]);
      b([0.055,1.1,0.055],[0,0.62,0],wood);
      b([0.38,0.3,0.38],[0,1.32,0],light,true);
      b([0.42,0.045,0.42],[0,1.4925,0]);
      break;
    case 'wall-light':
      b([0.18,0.36,0.05],[0,0.18,-0.07],wood);
      b([0.22,0.22,0.2],[0,0.18,0.055],light,true);
      b([0.25,0.035,0.22],[0,0.3075,0.055]);
      break;
    case 'pendant-light':
      b([0.5,0.045,0.5],[0,0.0225,0],light,true);
      b([0.55,0.18,0.55],[0,0.135,0]);
      b([0.03,0.7,0.03],[0,0.575,0],ink);
      b([0.14,0.035,0.14],[0,0.9425,0]);
      break;
    case 'succulent':
      pot();
      for(const x of [-0.095,0,0.095]) for(const z of [-0.075,0.075])
        b([0.07,0.08+(x===0?0.08:0),0.08],[x,0.285+(x===0?0.04:0),z],leaf);
      break;
    case 'cactus':
      pot();
      b([0.08,0.42,0.08],[0,0.46,0],leaf);
      for(const x of [-0.095,0.095]) {
        b([0.14,0.06,0.065],[x/2,0.43,0],leaf);
        b([0.065,0.14,0.065],[x,0.47,0],leaf);
      }
      b([0.075,0.04,0.075],[0,0.69,0],'#e9b8b5');
      break;
    case 'fern':
      pot();
      b([0.035,0.32,0.035],[0,0.41,0],wood);
      for(let i=0;i<3;i++) for(const side of [-1,1]) {
        b([0.18-i*0.035,0.045,0.065],[side*(0.12-i*0.02),0.34+i*0.095,0],leaf);
        b([0.065,0.045,0.18-i*0.035],[0,0.37+i*0.095,side*(0.12-i*0.02)],'#9eaf7f');
      }
      break;
    case 'trailing-plant':
      // The root stays at the lowest leaf, so floor placement never buries foliage.
      b([0.28,0.22,0.28],[0,0.97,-0.1]);
      b([0.3,0.035,0.3],[0,1.095,-0.1]);
      b([0.25,0.07,0.25],[0,1.145,-0.1],leaf);
      for(let strand=0;strand<3;strand++) {
        const x=-0.115+strand*0.115,n=7-strand;
        b([0.02,n*0.13,0.02],[x,1.1-n*0.065,0.08],wood);
        for(let i=0;i<n;i++) b([0.08,0.09,0.045],[x+(i%2?0.028:-0.028),0.975-i*0.145,0.09],i%2 ? leaf : '#9eaf7f');
      }
      break;
    case 'flower-vase':
      b([0.17,0.22,0.17],[0,0.11,0]);
      for(let i=0;i<3;i++) {
        const x=-0.08+i*0.08,h=0.38+(i%2)*0.1;
        b([0.016,h-0.2,0.016],[x,(h+0.2)/2,0],leaf);
        b([0.12,0.045,0.045],[x,h,0],i%2?'#cabddd':'#e9b8b5');
        b([0.045,0.045,0.12],[x,h,0],i%2?'#cabddd':'#e9b8b5');
        b([0.035,0.025,0.035],[x,h+0.025,0],light);
      }
      break;
    default: return false;
  }
  return true;
}
